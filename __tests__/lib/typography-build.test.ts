/**
 * RAD-363 typography build (cycle B2) — generated @font-face + token bundles.
 * Spec: .tdd/spec-typography-build.md. Pure modules: inputs -> outputs, no
 * mocks. The filesystem is touched only for file existence (AC-13) and the
 * committed-file freshness check (AC-14).
 */

import { describe, it, expect } from "vitest"
import { readFileSync, existsSync } from "fs"
import path from "path"

import metrics from "@/lib/typography/font-metrics.json"
import { FONT_IDS, ROLES, FONTS, FIGURES_FACE, fontStack } from "@/lib/typography/fonts"
import { sizeAdjust, verticalOverrides, weightMap } from "@/lib/typography/derive"
import { ROLE_TOKENS } from "@/lib/typography/css"
import { DESIGN } from "@/lib/typography/design"
import { roleTokens, buildTokenCss, buildFontFaceCss } from "@/lib/typography/build"

const ROOT = path.resolve(__dirname, "../..")
const HEADER = "/* Generated by scripts/typography/build-css.ts — do not edit. */"

/** Literal copy of the spec's token order — ROLE_TOKENS may still be a stub. */
const TOKENS = [
  "family",
  "stretch",
  "wa",
  "wb",
  "size-adjust",
  "caps-adjust",
  "features",
  "df",
  "cf",
  "leading",
]

type Face = {
  location: Record<string, number>
  axes: Record<string, number[]>
  files?: { path: string; unicodeRange: string }[]
}
const FACES = metrics.faces as unknown as Record<string, Face>

/** value × 100, 2 decimals, trailing zeros dropped, plus "%". */
const pct = (v: number) => `${Number((v * 100).toFixed(2))}%`

type Rule = Record<string, string>

function fontFaceRules(css: string): Rule[] {
  const blocks = [...css.matchAll(/@font-face\s*\{([^}]*)\}/g)].map((m) => m[1])
  return blocks.map((body) => {
    const rule: Rule = {}
    for (const m of body.matchAll(/([a-z-]+)\s*:\s*([^;]+);/g)) rule[m[1]] = m[2].trim()
    return rule
  })
}

function ruleFor(css: string, family: string): Rule {
  const matches = fontFaceRules(css).filter((r) => r["font-family"] === family)
  expect(matches.length).toBe(1)
  return matches[0]
}

function declarations(css: string): [string, string][] {
  return [...css.matchAll(/(--[a-z0-9-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()])
}

describe("typography build (RAD-363 B2)", () => {
  it("AC-1: DESIGN holds features, tracking and leading for all eleven fonts", () => {
    const expected = {
      inter: { features: ["cv11", "ss01"], displayTracking: 0.25, capsTracking: 1, textLeading: 1 },
      "martian-grotesk": { features: ["kern"], displayTracking: 1, capsTracking: 0.8, textLeading: 1 },
      "pt-root-ui": { features: ["kern"], displayTracking: 0.8, capsTracking: 1, textLeading: 1 },
      "golos-text": { features: ["kern"], displayTracking: 0.8, capsTracking: 1, textLeading: 1 },
      "ibm-plex-sans": { features: ["kern"], displayTracking: 0.8, capsTracking: 1, textLeading: 1 },
      "sf-pro": { features: ["kern"], displayTracking: 0.6, capsTracking: 1, textLeading: 1 },
      "sf-pro-rounded": { features: ["kern"], displayTracking: 0.6, capsTracking: 1, textLeading: 1 },
      "martian-mono": { features: ["kern"], displayTracking: 0.4, capsTracking: 0.5, textLeading: 1.04 },
      "jetbrains-mono": { features: ["kern", "-calt"], displayTracking: 0.4, capsTracking: 0.5, textLeading: 1.04 },
      "ibm-plex-mono": { features: ["kern"], displayTracking: 0.4, capsTracking: 0.5, textLeading: 1.04 },
      "sf-mono": { features: ["kern"], displayTracking: 0.4, capsTracking: 0.5, textLeading: 1.04 },
    }
    expect(Object.keys(DESIGN).sort()).toEqual([...FONT_IDS].sort())
    for (const id of FONT_IDS) {
      const d = DESIGN[id]
      expect({
        features: [...d.features],
        displayTracking: d.displayTracking,
        capsTracking: d.capsTracking,
        textLeading: d.textLeading,
      }).toEqual(expected[id])
    }
  })

  it("AC-2: roleTokens(inter, text) is the identity bundle, bar the Display-cut tracking factor, in ROLE_TOKENS order", () => {
    const tokens = roleTokens("inter", "text")
    expect(tokens).toEqual({
      family: "var(--font-inter), ui-sans-serif, system-ui, sans-serif",
      stretch: "100%",
      wa: "1",
      wb: "0",
      "size-adjust": "none",
      "caps-adjust": "none",
      features: '"cv11", "ss01"',
      df: "0.25",
      cf: "1",
      leading: "1",
    })
    expect(Object.keys(tokens)).toEqual(TOKENS)
    expect([...ROLE_TOKENS]).toEqual(TOKENS)
  })

  it("AC-3: martian-grotesk tag uses the narrow face; counter prepends the Figures family", () => {
    const tag = roleTokens("martian-grotesk", "tag")
    expect({
      stretch: tag.stretch,
      wa: tag.wa,
      wb: tag.wb,
      "size-adjust": tag["size-adjust"],
      "caps-adjust": tag["caps-adjust"],
      features: tag.features,
      df: tag.df,
      cf: tag.cf,
      leading: tag.leading,
    }).toEqual({
      stretch: "87.5%",
      wa: "1.3376",
      wb: "-212.2362",
      "size-adjust": "none",
      "caps-adjust": "none",
      features: '"kern"',
      df: "1",
      cf: "0.8",
      leading: "1",
    })
    const counter = roleTokens("martian-grotesk", "counter")
    expect(counter.family).toBe(
      '"Radaric Martian Grotesk Figures", "Radaric Martian Grotesk", var(--font-inter), system-ui, sans-serif',
    )
    expect(counter.stretch).toBe("100%")
  })

  it("AC-4: martian-mono text leading, tracking and narrow tag width", () => {
    const text = roleTokens("martian-mono", "text")
    expect({ stretch: text.stretch, leading: text.leading, df: text.df, cf: text.cf }).toEqual({
      stretch: "100%",
      leading: "1.04",
      df: "0.4",
      cf: "0.5",
    })
    expect(roleTokens("martian-mono", "tag").stretch).toBe("87.5%")
    expect(roleTokens("martian-mono", "heading").leading).toBe("1")
  })

  it("AC-5: size-normalisation tokens for system and caps-adjusted fonts", () => {
    const pick = (id: string) => {
      const t = roleTokens(id, "text")
      return { "size-adjust": t["size-adjust"], "caps-adjust": t["caps-adjust"] }
    }
    expect(pick("sf-pro")).toEqual({ "size-adjust": "0.5459", "caps-adjust": "0.5459" })
    expect(pick("sf-pro-rounded")).toEqual({
      "size-adjust": "0.5459",
      "caps-adjust": "cap-height 0.7275",
    })
    expect(pick("pt-root-ui")).toEqual({ "size-adjust": "none", "caps-adjust": "cap-height 0.7275" })
    const mono = roleTokens("sf-mono", "text")
    expect({
      wa: mono.wa,
      wb: mono.wb,
      "size-adjust": mono["size-adjust"],
      "caps-adjust": mono["caps-adjust"],
    }).toEqual({ wa: "1.0784", wb: "-21.8829", "size-adjust": "0.5459", "caps-adjust": "0.5459" })
  })

  it("AC-6: in the counter role size-adjust equals the font's caps-adjust", () => {
    const expected: Record<string, string> = {
      inter: "none",
      "martian-grotesk": "none",
      "pt-root-ui": "cap-height 0.7275",
      "golos-text": "none",
      "ibm-plex-sans": "cap-height 0.7275",
      "sf-pro": "0.5459",
      "sf-pro-rounded": "cap-height 0.7275",
      "martian-mono": "none",
      "jetbrains-mono": "none",
      "ibm-plex-mono": "cap-height 0.7275",
      "sf-mono": "0.5459",
    }
    const actual: Record<string, [string, string]> = {}
    for (const id of FONT_IDS) {
      const t = roleTokens(id, "counter")
      actual[id] = [t["size-adjust"], t["caps-adjust"]]
    }
    expect(actual).toEqual(
      Object.fromEntries(FONT_IDS.map((id) => [id, [expected[id], expected[id]]])),
    )
  })

  it("AC-7: every font × role derives weight, width and family from its face", () => {
    const actual: Record<string, Record<string, string>> = {}
    const expected: Record<string, Record<string, string>> = {}
    for (const id of FONT_IDS) {
      for (const role of ROLES) {
        const faceId = role === "tag" ? FONTS[id].faces.narrow : FONTS[id].faces.standard
        const wm = weightMap(faceId)
        const t = roleTokens(id, role)
        const key = `${id}/${role}`
        actual[key] = { wa: t.wa, wb: t.wb, stretch: t.stretch, family: t.family }
        expected[key] = {
          wa: String(wm.a),
          wb: String(wm.b),
          stretch: pct((FACES[faceId].location.wdth ?? 100) / 100),
          family: fontStack(id, role),
        }
      }
    }
    expect(Object.keys(actual).length).toBe(44)
    expect(actual).toEqual(expected)
  })

  it("AC-8: buildTokenCss emits 440 font tokens then 40 default role mappings in @layer base :root", () => {
    const css = buildTokenCss()
    expect(css.startsWith(HEADER)).toBe(true)
    const layer = css.indexOf("@layer base {")
    const root = css.indexOf(":root {")
    const firstDecl = css.indexOf("--")
    expect(layer > HEADER.length - 1 && root > layer && firstDecl > root).toBe(true)

    const expected: [string, string][] = []
    for (const id of FONT_IDS) {
      for (const role of ROLES) {
        const t = roleTokens(id, role)
        for (const token of TOKENS) expected.push([`--f-${id}-${role}-${token}`, t[token]])
      }
    }
    for (const role of ROLES) {
      for (const token of TOKENS) {
        expected.push([`--type-${role}-${token}`, `var(--f-inter-${role}-${token})`])
      }
    }
    const decls = declarations(css)
    expect(decls.length).toBe(480)
    expect(new Set(decls.map(([n]) => n)).size).toBe(480)
    expect(decls).toEqual(expected)
  })

  it("AC-9: buildFontFaceCss emits one rule per self-hosted file, in registry order", () => {
    const css = buildFontFaceCss()
    expect(css.startsWith(HEADER)).toBe(true)
    expect(fontFaceRules(css).map((r) => r["font-family"])).toEqual([
      '"Radaric Martian Grotesk"',
      '"Radaric Martian Grotesk Figures"',
      '"Radaric PT Root UI"',
      '"Radaric Golos Text"',
      '"Radaric IBM Plex Sans"',
      '"Radaric IBM Plex Sans"',
      '"Radaric IBM Plex Sans"',
      '"Radaric IBM Plex Sans"',
      '"Radaric IBM Plex Sans"',
      '"Radaric IBM Plex Sans"',
      '"Radaric Martian Mono"',
      '"Radaric JetBrains Mono"',
      '"Radaric IBM Plex Mono"',
      '"Radaric IBM Plex Mono"',
      '"Radaric IBM Plex Mono"',
      '"Radaric IBM Plex Mono"',
    ])
  })

  it("AC-9b: the new variable faces carry their own axis ranges and metrics", () => {
    const css = buildFontFaceCss()
    const golos = ruleFor(css, '"Radaric Golos Text"')
    expect({
      src: golos.src,
      "font-weight": golos["font-weight"],
      "has-font-stretch": "font-stretch" in golos,
      "size-adjust": golos["size-adjust"],
      "ascent-override": golos["ascent-override"],
    }).toEqual({
      src: 'url("./golos-text/GolosText-VF.woff2") format("woff2")',
      "font-weight": "400 900",
      "has-font-stretch": false,
      "size-adjust": "103%",
      "ascent-override": "93.74%",
    })
    const jetbrains = ruleFor(css, '"Radaric JetBrains Mono"')
    expect([jetbrains["font-weight"], "font-stretch" in jetbrains, jetbrains["size-adjust"]]).toEqual([
      "100 800",
      false,
      "99.25%",
    ])
    const plex = fontFaceRules(css).filter((r) => r["font-family"] === '"Radaric IBM Plex Sans"')
    expect(plex.map((r) => [r.src, r["font-weight"], r["font-stretch"]])).toEqual([
      ['url("./ibm-plex-sans/IBMPlexSansVar-Roman-Latin1.woff2") format("woff2")', "100 700", "85% 100%"],
      ['url("./ibm-plex-sans/IBMPlexSansVar-Roman-Latin2.woff2") format("woff2")', "100 700", "85% 100%"],
      ['url("./ibm-plex-sans/IBMPlexSansVar-Roman-Latin3.woff2") format("woff2")', "100 700", "85% 100%"],
      ['url("./ibm-plex-sans/IBMPlexSansVar-Roman-Greek.woff2") format("woff2")', "100 700", "85% 100%"],
      ['url("./ibm-plex-sans/IBMPlexSansVar-Roman-Cyrillic.woff2") format("woff2")', "100 700", "85% 100%"],
      ['url("./ibm-plex-sans/IBMPlexSansVar-Roman-Pi.woff2") format("woff2")', "100 700", "85% 100%"],
    ])
    for (const rule of plex) {
      expect([rule["size-adjust"], rule["ascent-override"], rule["descent-override"]]).toEqual([
        "105.79%",
        "92.09%",
        "22.29%",
      ])
    }
  })

  it("AC-9c: a static face emits one rule per file, each pinned to its own single weight", () => {
    const rules = fontFaceRules(buildFontFaceCss()).filter((r) => r["font-family"] === '"Radaric IBM Plex Mono"')
    expect(rules.map((r) => [r.src, r["font-weight"], "font-stretch" in r])).toEqual([
      ['url("./ibm-plex-mono/IBMPlexMono-Regular.woff2") format("woff2")', "400", false],
      ['url("./ibm-plex-mono/IBMPlexMono-Medium.woff2") format("woff2")', "500", false],
      ['url("./ibm-plex-mono/IBMPlexMono-SemiBold.woff2") format("woff2")', "600", false],
      ['url("./ibm-plex-mono/IBMPlexMono-Bold.woff2") format("woff2")', "700", false],
    ])
    for (const rule of rules) {
      expect([rule["size-adjust"], rule["ascent-override"], rule["descent-override"]]).toEqual([
        "105.79%",
        "92.09%",
        "22.29%",
      ])
    }
  })

  it("AC-9d: jetbrains-mono emits the calt disable in every role; no other font's features token changed", () => {
    const expected: Record<string, string> = {
      inter: '"cv11", "ss01"',
      "martian-grotesk": '"kern"',
      "pt-root-ui": '"kern"',
      "golos-text": '"kern"',
      "ibm-plex-sans": '"kern"',
      "sf-pro": '"kern"',
      "sf-pro-rounded": '"kern"',
      "martian-mono": '"kern"',
      "jetbrains-mono": '"kern", "calt" 0',
      "ibm-plex-mono": '"kern"',
      "sf-mono": '"kern"',
    }
    const actual: Record<string, string[]> = {}
    for (const id of FONT_IDS) {
      actual[id] = ROLES.map((role) => roleTokens(id, role).features)
    }
    expect(actual).toEqual(Object.fromEntries(FONT_IDS.map((id) => [id, ROLES.map(() => expected[id])])))
    for (const id of FONT_IDS) {
      for (const role of ROLES) {
        expect(roleTokens(id, role).features, `${id}/${role}`).not.toMatch(/(^|")\s*-/)
      }
    }
    // `.uppercase` appends `, "case"` to whatever the role carries — the disable composes too.
    expect(`${roleTokens("jetbrains-mono", "text").features}, "case"`).toBe('"kern", "calt" 0, "case"')
  })

  it("AC-10: the Martian Grotesk rule carries the normalising descriptors", () => {
    const rule = ruleFor(buildFontFaceCss(), '"Radaric Martian Grotesk"')
    const { "font-family": _family, ...rest } = rule
    expect(rest).toEqual({
      src: 'url("./martian-grotesk/MartianGrotesk-VFVF.woff2") format("woff2")',
      "font-weight": "100 1000",
      "font-stretch": "75% 200%",
      "font-style": "normal",
      "font-display": "swap",
      "size-adjust": "90.98%",
      "ascent-override": "106.5%",
      "descent-override": "26.5%",
      "line-gap-override": "0%",
      "unicode-range": FACES["martian-grotesk"].files![0].unicodeRange,
    })
  })

  it("AC-11: Martian Mono and PT Root UI rules use their own axis ranges and metrics", () => {
    const css = buildFontFaceCss()
    const mono = ruleFor(css, '"Radaric Martian Mono"')
    expect([mono["font-weight"], mono["font-stretch"]]).toEqual(["100 800", "75% 112.5%"])
    const pt = ruleFor(css, '"Radaric PT Root UI"')
    expect({
      src: pt.src,
      "font-weight": pt["font-weight"],
      "has-font-stretch": "font-stretch" in pt,
      "size-adjust": pt["size-adjust"],
      "ascent-override": pt["ascent-override"],
      "descent-override": pt["descent-override"],
    }).toEqual({
      src: 'url("./pt-root-ui/PT-Root-UI-VF.woff2") format("woff2")',
      "font-weight": "300 700",
      "has-font-stretch": false,
      "size-adjust": "109.18%",
      "ascent-override": "90.41%",
      "descent-override": "20.41%",
    })
  })

  it("AC-12: the Figures face is digits-only Martian Mono pinned to the narrow width", () => {
    const rule = ruleFor(buildFontFaceCss(), '"Radaric Martian Grotesk Figures"')
    const figuresFace = FIGURES_FACE["martian-grotesk"]
    const v = verticalOverrides(figuresFace)
    expect({
      src: rule.src,
      "unicode-range": rule["unicode-range"],
      "font-stretch": rule["font-stretch"],
      "font-weight": rule["font-weight"],
      "size-adjust": rule["size-adjust"],
      "ascent-override": rule["ascent-override"],
      "descent-override": rule["descent-override"],
      "line-gap-override": rule["line-gap-override"],
    }).toEqual({
      src: 'url("./martian-mono/MartianMonoVF.woff2") format("woff2")',
      "unicode-range": "U+0030-0039",
      "font-stretch": "87.5%",
      "font-weight": "100 800",
      "size-adjust": pct(sizeAdjust(figuresFace)),
      "ascent-override": pct(v.ascent),
      "descent-override": pct(v.descent),
      "line-gap-override": "0%",
    })
  })

  it("AC-13: every Radaric family in a stack has its expected rules (Plex Sans is split), and every url exists", () => {
    const css = buildFontFaceCss()
    const families = new Set<string>()
    for (const id of FONT_IDS) {
      for (const role of ROLES) {
        for (const m of fontStack(id, role).matchAll(/"(Radaric [^"]+)"/g)) families.add(`"${m[1]}"`)
      }
    }
    const declared = fontFaceRules(css).map((r) => r["font-family"])
    const counts = [...families].sort().map((f) => [f, declared.filter((d) => d === f).length])
    // IBM Plex Sans ships as six official per-script splits; IBM Plex Mono as
    // four static weights; every other family is one file.
    const expectedPerFamily: Record<string, number> = {
      '"Radaric IBM Plex Sans"': 6,
      '"Radaric IBM Plex Mono"': 4,
    }
    expect(counts).toEqual(
      [...families].sort().map((f) => [f, expectedPerFamily[f] ?? 1]),
    )

    const urls = [...css.matchAll(/url\("\.\/([^"]+)"\)/g)].map((m) => m[1])
    expect(urls.length).toBe(16)
    const missing = urls.filter((u) => !existsSync(path.join(ROOT, "app/fonts", u)))
    expect(missing).toEqual([])
  })

  it("AC-14: the committed stylesheets equal the builder output byte for byte", () => {
    const fontsCss = path.join(ROOT, "app/fonts/fonts.css")
    const typographyCss = path.join(ROOT, "app/typography.css")
    expect([existsSync(fontsCss), existsSync(typographyCss)]).toEqual([true, true])
    expect(readFileSync(fontsCss, "utf8")).toBe(buildFontFaceCss())
    expect(readFileSync(typographyCss, "utf8")).toBe(buildTokenCss())
  })

  it("EC-1: faces sharing a file agree on size and vertical descriptors", () => {
    for (const id of ["martian-grotesk", "martian-mono"]) {
      const { standard, narrow } = FONTS[id].faces
      expect(FACES[standard].files![0].path).toBe(FACES[narrow].files![0].path)
      expect(sizeAdjust(narrow)).toBe(sizeAdjust(standard))
      expect(verticalOverrides(narrow)).toEqual(verticalOverrides(standard))
    }
  })

  it("ERR-1: roleTokens throws on an unknown font or role, naming it", () => {
    expect(() => roleTokens("comic-sans", "text")).toThrow(/comic-sans/)
    expect(() => roleTokens("constructor", "text")).toThrow(/constructor/)
    expect(() => roleTokens("inter", "body")).toThrow(/body/)
  })
})
