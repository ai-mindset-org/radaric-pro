/**
 * Typography CSS builders (RAD-363) — the `@font-face` rules for the
 * self-hosted faces and the static per-font token bundles, generated into
 * `app/fonts/fonts.css` and `app/typography.css` by
 * `scripts/typography/build-css.ts`. Pure: no filesystem, no network.
 * Spec: .tdd/spec-typography-build.md.
 */
import { ROLE_TOKENS } from "./css"
import { sizeAdjust, verticalOverrides, weightMap, needsCapsAdjust } from "./derive"
import { DESIGN } from "./design"
import metrics from "./font-metrics.json"
import { FIGURES_FACE, FONTS, FONT_IDS, ROLES, fontStack, isFontId, isRole } from "./fonts"

interface FaceFile {
  path: string
  unicodeRange: string
  weight?: number
}

interface FaceMetrics {
  axes: Record<string, number[]>
  location: Record<string, number>
  capHeight: number
  xHeight: number
  files?: FaceFile[]
  static?: boolean
  system?: string
}

const FACES = metrics.faces as unknown as Record<string, FaceMetrics>
const REFERENCE = FACES[metrics.reference]

const HEADER = "/* Generated by scripts/typography/build-css.ts — do not edit. */"
const FONTS_DIR = "app/fonts/"
/** Loaded through `next/font/local`, so it gets no rule here. */
const NEXT_FONT = "inter"
const DIGITS = "U+0030-0039"

/** value × 100, 2 decimals, trailing zeros dropped, plus "%". */
const pct = (v: number) => `${Number((v * 100).toFixed(2))}%`

const family = (id: string) => `"Radaric ${FONTS[id].label}"`

/** The `size-adjust` token: `none` for shipped faces, the reference x-height for system ones. */
function sizeToken(faceId: string): string {
  return FACES[faceId].system ? REFERENCE.xHeight.toFixed(4) : "none"
}

/** The ten token values for a font in a role, in `ROLE_TOKENS` order. */
export function roleTokens(fontId: string, role: string): Record<string, string> {
  if (!isFontId(fontId)) throw new Error(`Unknown font id: ${fontId}`)
  if (!isRole(role)) throw new Error(`Unknown typography role: ${role}`)
  const { faces } = FONTS[fontId]
  const faceId = role === "tag" ? faces.narrow : faces.standard
  const design = DESIGN[fontId]
  const { a, b } = weightMap(faceId)
  const size = sizeToken(faceId)
  const caps = needsCapsAdjust(faceId) ? `cap-height ${REFERENCE.capHeight.toFixed(4)}` : size
  const values: Record<(typeof ROLE_TOKENS)[number], string> = {
    family: fontStack(fontId, role),
    stretch: pct((FACES[faceId].location.wdth ?? 100) / 100),
    wa: String(a),
    wb: String(b),
    "size-adjust": role === "counter" ? caps : size,
    "caps-adjust": caps,
    // A `-tag` entry disables the feature: `"calt" 0`, not `"calt"`.
    features: design.features.map((f) => (f.startsWith("-") ? `"${f.slice(1)}" 0` : `"${f}"`)).join(", "),
    df: String(design.displayTracking),
    cf: String(design.capsTracking),
    leading: String(role === "text" ? design.textLeading : 1),
  }
  return Object.fromEntries(ROLE_TOKENS.map((token) => [token, values[token]]))
}

/** Every `--f-<font>-<role>-<token>` bundle, then the Inter default `--type-*` mapping. */
export function buildTokenCss(): string {
  const lines: string[] = []
  for (const id of FONT_IDS) {
    for (const role of ROLES) {
      const tokens = roleTokens(id, role)
      for (const token of ROLE_TOKENS) lines.push(`--f-${id}-${role}-${token}: ${tokens[token]};`)
    }
  }
  for (const role of ROLES) {
    for (const token of ROLE_TOKENS) {
      lines.push(`--type-${role}-${token}: var(--f-${NEXT_FONT}-${role}-${token});`)
    }
  }
  return `${HEADER}\n\n@layer base {\n  :root {\n${lines.map((l) => `    ${l}`).join("\n")}\n  }\n}\n`
}

function range(values: number[], format: (v: number) => string): string {
  const [min, , max] = values
  return `${format(min)} ${format(max)}`
}

/** The size and vertical descriptors that normalise a face. */
function metricDescriptors(faceId: string): string[] {
  const v = verticalOverrides(faceId)
  return [
    `size-adjust: ${pct(sizeAdjust(faceId))}`,
    `ascent-override: ${pct(v.ascent)}`,
    `descent-override: ${pct(v.descent)}`,
    `line-gap-override: ${pct(v.lineGap)}`,
  ]
}

function fontFace(
  name: string,
  faceId: string,
  file: FaceFile,
  stretch: string | null,
  unicodeRange: string,
): string {
  const url = `./${file.path.slice(FONTS_DIR.length)}`
  // A static face pins one weight per file; a variable one declares its axis range.
  const weight = file.weight !== undefined ? String(file.weight) : range(FACES[faceId].axes.wght, String)
  const descriptors = [
    `font-family: ${name}`,
    `src: url("${url}") format("woff2")`,
    `font-weight: ${weight}`,
    ...(stretch ? [`font-stretch: ${stretch}`] : []),
    "font-style: normal",
    "font-display: swap",
    ...metricDescriptors(faceId),
    `unicode-range: ${unicodeRange}`,
  ]
  return `@font-face {\n${descriptors.map((d) => `  ${d};`).join("\n")}\n}`
}

const sameMetrics = (x: string, y: string) =>
  JSON.stringify([sizeAdjust(x), verticalOverrides(x)]) === JSON.stringify([sizeAdjust(y), verticalOverrides(y)])

/** One rule per self-hosted file (Inter excepted), plus the digits-only Figures faces. */
export function buildFontFaceCss(): string {
  const rules: string[] = []
  for (const id of FONT_IDS) {
    if (id === NEXT_FONT || FONTS[id].source !== "self-hosted") continue
    const byFile = new Map<string, string>()
    for (const faceId of [FONTS[id].faces.standard, FONTS[id].faces.narrow]) {
      for (const file of FACES[faceId].files ?? []) {
        const seen = byFile.get(file.path)
        if (seen === undefined) byFile.set(file.path, faceId)
        else if (!sameMetrics(seen, faceId)) {
          throw new Error(`Faces ${seen} and ${faceId} share ${file.path} but disagree on metrics`)
        }
      }
    }
    for (const [path, faceId] of byFile) {
      const file = FACES[faceId].files!.find((f) => f.path === path)!
      const wdth = FACES[faceId].axes.wdth
      const stretch = wdth ? range(wdth, (v) => pct(v / 100)) : null
      rules.push(fontFace(family(id), faceId, file, stretch, file.unicodeRange))
    }
    if (Object.hasOwn(FIGURES_FACE, id)) {
      const faceId = FIGURES_FACE[id]
      const face = FACES[faceId]
      const stretch = pct(face.location.wdth / 100)
      rules.push(fontFace(`"Radaric ${FONTS[id].label} Figures"`, faceId, face.files![0], stretch, DIGITS))
    }
  }
  return `${HEADER}\n\n${rules.join("\n\n")}\n`
}
